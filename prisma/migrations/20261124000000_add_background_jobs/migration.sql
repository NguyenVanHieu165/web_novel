CREATE TABLE `background_jobs` (
  `id` VARCHAR(36) NOT NULL,
  `type` VARCHAR(50) NOT NULL,
  `status` VARCHAR(20) NOT NULL DEFAULT 'queued',
  `payload` JSON NOT NULL,
  `result` JSON NULL,
  `progress` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `priority` SMALLINT NOT NULL DEFAULT 0,
  `attempts` INT UNSIGNED NOT NULL DEFAULT 0,
  `max_attempts` INT UNSIGNED NOT NULL DEFAULT 3,
  `run_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `locked_by` VARCHAR(100) NULL,
  `lease_expires_at` DATETIME(3) NULL,
  `heartbeat_at` DATETIME(3) NULL,
  `dedupe_key` VARCHAR(191) NULL,
  `owner_id` INT NULL,
  `last_error` TEXT NULL,
  `started_at` DATETIME(3) NULL,
  `finished_at` DATETIME(3) NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE INDEX `uk_background_jobs_dedupe_key` (`dedupe_key`),
  INDEX `idx_background_jobs_claim` (`status`, `run_at`, `priority`, `created_at`),
  INDEX `idx_background_jobs_lease` (`status`, `lease_expires_at`),
  INDEX `idx_background_jobs_owner_created_at` (`owner_id`, `created_at`),
  CONSTRAINT `background_jobs_ibfk_1` FOREIGN KEY (`owner_id`)
    REFERENCES `tai_khoan` (`idTAI_KHOAN`) ON DELETE SET NULL ON UPDATE NO ACTION
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
